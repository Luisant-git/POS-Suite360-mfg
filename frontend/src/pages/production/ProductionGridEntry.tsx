import { useState, useEffect } from 'react';
import { useQuery, useMutation } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import toast from 'react-hot-toast';
import { CheckCircle, PlusCircle, RotateCcw, List, Plus, Trash2, FileText, ArrowLeft, Factory } from 'lucide-react';
import api from '../../services/api';
import SearchableSelect from '../../components/SearchableSelect';
import ShortcutHelpButton from '../../components/ShortcutHelp';
import LeaveConfirmModal from '../../components/LeaveConfirmModal';

const generateBatchName = (prods: any[]) => {
  if (!prods || prods.length === 0) return 'BCH-0001';
  let maxNum = 0;
  prods.forEach(p => {
    if (p.workName) {
      const match = String(p.workName).match(/BCH-(\d+)/i);
      if (match) {
        const num = parseInt(match[1], 10);
        if (num > maxNum) maxNum = num;
      }
    }
  });
  return `BCH-${String(maxNum + 1).padStart(4, '0')}`;
};

const ProductionGridEntry = ({ onSwitchToMaster }: { onSwitchToMaster?: () => void }) => {
  const navigate = useNavigate();
  const [date, setDate] = useState(new Date().toISOString().split('T')[0]);
  const [workName, setWorkName] = useState('');
  const [batchCode, setBatchCode] = useState('');
  const [showLeaveModal, setShowLeaveModal] = useState(false);
  
  const [items, setItems] = useState<any[]>([
    { rawMaterialId: 0, sqM: '', intakeQuantity: '', finishedProductId: 0, outcomeQuantity: '' }
  ]);

  const { data: rawMaterials = [] } = useQuery({ 
    queryKey: ['rawMaterials'], 
    queryFn: async () => (await api.get('/raw-materials')).data 
  });

  const { data: products = [] } = useQuery({ 
    queryKey: ['products'], 
    queryFn: async () => (await api.get('/products')).data 
  });

  const { data: productions = [], isLoading } = useQuery({
    queryKey: ['productions'],
    queryFn: async () => (await api.get('/production')).data
  });

  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);

  useEffect(() => {
    if (!isLoading && !hasAutoGenerated && !batchCode && productions) {
      setBatchCode(generateBatchName(productions));
      setHasAutoGenerated(true);
    }
  }, [isLoading, hasAutoGenerated, batchCode, productions]);

  // Auto-focus first row product on mount
  useEffect(() => {
    const timer = setTimeout(() => {
      const el = document.querySelector<HTMLElement>('[data-row-product="0"]');
      el?.focus();
    }, 200);
    return () => clearTimeout(timer);
  }, []);

  const finishedProducts = products;

  const addItem = () => {
    setItems([...items, { rawMaterialId: 0, sqM: '', intakeQuantity: '', finishedProductId: 0, outcomeQuantity: '' }]);
  };

  const removeItem = (index: number) => {
    setItems(items.filter((_, i) => i !== index));
  };

  const handleClear = () => {
    setBatchCode(generateBatchName(productions));
    setWorkName('');
    setDate(new Date().toISOString().split('T')[0]);
    setItems([{ rawMaterialId: 0, sqM: '', intakeQuantity: '', finishedProductId: 0, outcomeQuantity: '' }]);
  };

  const updateItem = (index: number, field: string, value: any) => {
    const newItems = [...items];
    
    if (field === 'intakeQuantity') {
      const rawMaterialId = newItems[index].rawMaterialId;
      const material = rawMaterials.find((m: any) => m.id === rawMaterialId);
      const currentStock = material?.currentStock || 0;
      
      if (Number(value) > currentStock) {
        toast.error(`Quantity Intake cannot exceed Current Stock (${currentStock})`);
        return;
      }

      const sqMPerRoll = material?.rawMaterialPurchaseItems?.[0]?.sqM || 0;
      newItems[index].sqM = (Number(value) * Number(sqMPerRoll)).toFixed(3);
    }
    
    if (field === 'rawMaterialId') {
      const material = rawMaterials.find((m: any) => m.id === Number(value));
      const sqMPerRoll = material?.rawMaterialPurchaseItems?.[0]?.sqM || 0;
      const currentQty = Number(newItems[index].intakeQuantity) || 0;
      newItems[index].sqM = (currentQty * Number(sqMPerRoll)).toFixed(3);
    }

    if (field === 'finishedProductId') {
      const product = products.find((p: any) => p.id === Number(value));
      newItems[index].finishedProductId = value;

      if (product && product.rawMaterials && product.rawMaterials.length > 0) {
        // Update current row with the first raw material
        const autoRawMatId = product.rawMaterials[0].rawMaterialId;
        newItems[index].rawMaterialId = autoRawMatId;
        
        // Recalculate sqM
        const material = rawMaterials.find((m: any) => m.id === autoRawMatId);
        const sqMPerRoll = material?.rawMaterialPurchaseItems?.[0]?.sqM || 0;
        const currentQty = Number(newItems[index].intakeQuantity) || 0;
        newItems[index].sqM = (currentQty * Number(sqMPerRoll)).toFixed(3);

        // If there are multiple raw materials, insert additional rows
        if (product.rawMaterials.length > 1) {
          const additionalItems = product.rawMaterials.slice(1).map((rmMap: any) => {
             const rmId = rmMap.rawMaterialId;
             const sqM = '0.000';
             return {
               rawMaterialId: rmId,
               sqM,
               intakeQuantity: '',
               finishedProductId: value,
               outcomeQuantity: newItems[index].outcomeQuantity || ''
             };
          });
          newItems.splice(index + 1, 0, ...additionalItems);
        }
      }
      setItems(newItems);
      // Navigate based on whether material was auto-filled
      setTimeout(() => {
        const materialFilled = newItems[index].rawMaterialId > 0;
        if (materialFilled) {
          // Skip material, go straight to Quantity Intake
          const el = document.querySelector<HTMLElement>(`[data-intake="${index}"]`);
          if (el) { el.focus(); (el as HTMLInputElement).select?.(); }
        } else {
          // Go to Material Name
          const el = document.querySelector<HTMLElement>(`[data-row-material="${index}"]`);
          if (el) el.focus();
        }
      }, 50);
      return;
    }

    newItems[index][field] = value;
    setItems(newItems);
  };

  const mutation = useMutation({
    mutationFn: async () => {
      const finalWorkName = batchCode ? `${batchCode} - ${workName}` : workName;
      const validItems = items.filter(i => i.rawMaterialId > 0 && i.finishedProductId > 0);
      
      // Submit multiple production entries concurrently
      const promises = validItems.map(item => {
        const payload = {
          date,
          workName: finalWorkName,
          rawMaterialId: parseInt(item.rawMaterialId),
          intakeQuantity: parseInt(item.intakeQuantity || '0'),
          finishedProductId: parseInt(item.finishedProductId),
          outcomeQuantity: parseInt(item.outcomeQuantity || '0')
        };
        // The backend doesn't store quality currently, so we just drop it or we can ignore it for now.
        return api.post('/production', payload);
      });

      return Promise.all(promises);
    },
    onSuccess: () => {
      toast.success('Production entries saved successfully');
      handleClear();
    },
    onError: (err: any) => {
      console.error(err);
      toast.error('Failed to save production entries');
    }
  });

  const handleSubmit = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (!workName) {
      toast.error('Please fill Name of Work');
      return;
    }
    const validItems = items.filter(i => i.rawMaterialId > 0 && i.finishedProductId > 0);
    if (validItems.length === 0) {
      toast.error('Please add at least one complete production row.');
      return;
    }
    mutation.mutate();
  };

  // Keyboard Shortcuts
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'F10') {
        e.preventDefault();
        handleSubmit();
      } else if (e.key === 'F2') {
        e.preventDefault();
        addItem();
      } else if (e.key === 'F4') {
        e.preventDefault();
        handleClear();
      } else if (e.key === 'Escape') {
        if (!showLeaveModal) {
          setShowLeaveModal(true);
        }
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [handleSubmit, handleClear, showLeaveModal]);

  return (
    <div className="absolute inset-0 bg-[#F3F4F6] flex flex-col font-sans overflow-hidden z-10">
      
      {/* Top Bar */}


      <form className="hidden md:flex flex-col flex-1 min-h-0 overflow-hidden" onSubmit={handleSubmit}>
        
        {/* Header Section */}
        <div className="bg-white p-3 sm:p-4 border-b border-[#E5E7EB] shrink-0">
          <div className="grid grid-cols-1 md:grid-cols-2 lg:flex lg:flex-row gap-3 sm:gap-4">
            
            <div className="w-full lg:flex-1 lg:max-w-[200px]">
              <label className="block text-[11px] font-bold text-[#1F2937] mb-1">Production Date *</label>
              <input
                type="date"
                value={date}
                onChange={e => setDate(e.target.value)}
                className="w-full px-2 py-1.5 border border-[#D1D5DB] rounded text-[13px] outline-none focus:border-[#3B82F6]"
              />
            </div>

            <div className="w-full lg:flex-1 lg:max-w-[150px]">
              <label className="block text-[11px] font-bold text-[#1F2937] mb-1">Batch Code (Auto)</label>
              <input
                type="text"
                value={batchCode}
                readOnly
                className="w-full px-2 py-1.5 border border-[#D1D5DB] rounded text-[13px] outline-none bg-gray-100 text-gray-500 cursor-not-allowed"
              />
            </div>

            <div className="w-full lg:flex-[2] lg:max-w-[350px]">
              <label className="block text-[11px] font-bold text-[#1F2937] mb-1">Name of Work *</label>
              <input
                type="text"
                value={workName}
                onChange={e => setWorkName(e.target.value)}
                placeholder="e.g. Manufacturing A"
                className="w-full px-2 py-1.5 border border-[#D1D5DB] rounded text-[13px] outline-none focus:border-[#3B82F6]"
              />
            </div>
            
          </div>
        </div>

        {/* Action Buttons */}
        <div className="shrink-0 flex flex-wrap justify-between gap-2 p-2 bg-white border-b border-[#E5E7EB]">
          <div className="flex gap-2">
            <button type="button" onClick={() => { if (onSwitchToMaster) onSwitchToMaster(); }} className="border border-[#10B981] text-[#10B981] hover:bg-[#10B981] hover:text-white px-3 py-1 rounded flex items-center gap-1 text-[12px] transition-colors font-bold">
              <List size={14} /> List
            </button>
            <button type="button" onClick={() => navigate('/reports/production')} className="border border-[#8B5CF6] text-[#8B5CF6] hover:bg-[#8B5CF6] hover:text-white px-3 py-1 rounded flex items-center gap-1 text-[12px] transition-colors font-bold">
              <FileText size={14} /> Report
            </button>
            <button type="button" onClick={() => handleSubmit()} className="bg-[#10B981] hover:bg-[#059669] text-white px-3 py-1 rounded flex items-center gap-1 text-[12px] font-bold transition-colors">
              <CheckCircle size={14} /> Save Entry (F10)
            </button>
          </div>
          <div className="flex gap-2">
            <button type="button" onClick={addItem} className="border border-[#0B355B] text-[#0B355B] hover:bg-[#0B355B] hover:text-white px-3 py-1 rounded flex items-center gap-1 text-[12px] transition-colors font-bold">
              <PlusCircle size={14} /> Add Row
            </button>
            <button type="button" onClick={handleClear} className="border border-[#EF4444] text-[#EF4444] hover:bg-[#EF4444] hover:text-white px-3 py-1 rounded flex items-center gap-1 text-[12px] transition-colors font-bold">
              <RotateCcw size={14} /> Clear (F4)
            </button>
            <ShortcutHelpButton />
          </div>
        </div>

        {/* Items Grid */}
        <div className="flex-1 min-h-0 overflow-auto custom-scrollbar bg-white border-b border-[#E5E7EB]">
          <table className="w-full border-collapse border border-[#E5E7EB] md:min-w-[1200px] whitespace-nowrap responsive-table">
            <thead>
              <tr className="bg-[#0F172A] text-white">
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-10">#</th>
                <th className="px-2 py-2 text-left text-[12px] font-medium border border-[#334155] w-[250px]">Finished Product Name (Outcome)</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-24">Product Sq.M</th>
                <th className="px-2 py-2 text-left text-[12px] font-medium border border-[#334155] w-[250px]">Material Name (Intake)</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-24">Current Stock</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-24">Quantity Intake</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-32">RAW SQ.M</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-28">Outcome Products Count</th>
                <th className="px-2 py-2 text-center text-[12px] font-medium border border-[#334155] w-16">Act</th>
              </tr>
            </thead>
            <tbody>
              {items.map((item, index) => (
                <tr 
                  key={index} 
                  className="border-b border-[#E5E7EB] hover:bg-[#F9FAFB] transition-colors"
                  onKeyDown={(e) => {
                    if (e.key === 'Delete' && e.ctrlKey) {
                      e.preventDefault();
                      if (items.length > 1) {
                        removeItem(index);
                      }
                    }
                  }}
                >
                  <td className="px-2 py-1 text-center text-[13px] border-r border-[#E5E7EB] text-[#4B5563]">{index + 1}</td>
                  
                  {/* OUTCOME - Product */}
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <SearchableSelect
                      value={item.finishedProductId}
                      autoFocus={index === 0 && items.length === 1 && item.finishedProductId === 0}
                      dataAttr={{ 'data-row-product': String(index) }}
                      onChange={(val) => updateItem(index, 'finishedProductId', Number(val))}
                      options={[
                        { label: 'Type product...', value: 0 },
                        ...finishedProducts.map((p: any) => ({ label: `${p.name} (Stock: ${p.currentStock})`, value: p.id }))
                      ]}
                    />
                  </td>
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <input 
                      type="text" 
                      readOnly
                      tabIndex={-1}
                      value={products.find((p: any) => p.id === item.finishedProductId)?.sqM || '0.000'}
                      className="w-full px-2 py-1 border border-[#D1D5DB] rounded bg-[#E5E7EB] text-[13px] outline-none text-right font-bold text-[#4B5563] cursor-not-allowed"
                    />
                  </td>

                  {/* INTAKE */}
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <SearchableSelect
                      value={item.rawMaterialId}
                      dataAttr={{ 'data-row-material': String(index) }}
                      onTabNext={() => {
                        const el = document.querySelector<HTMLElement>(`[data-intake="${index}"]`);
                        if (el) { el.focus(); (el as HTMLInputElement).select?.(); }
                      }}
                      onChange={(val) => updateItem(index, 'rawMaterialId', Number(val))}
                      options={[
                        { label: 'Type material...', value: 0 },
                        ...rawMaterials.map((m: any) => ({ label: `${m.name}`, value: m.id }))
                      ]}
                    />
                  </td>
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <input 
                      type="text" 
                      readOnly
                      value={rawMaterials.find((m: any) => m.id === item.rawMaterialId)?.currentStock || 0}
                      className="w-full px-2 py-1 border border-[#D1D5DB] rounded bg-[#E5E7EB] text-[13px] outline-none text-right font-bold text-[#4B5563] cursor-not-allowed"
                    />
                  </td>
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <input 
                      type="number" value={item.intakeQuantity} onChange={e => updateItem(index, 'intakeQuantity', e.target.value)}
                      data-intake={index}
                      placeholder="0" onFocus={e => e.target.select()}
                      onKeyDown={(e) => {
                        if (e.key === 'Enter') {
                          e.preventDefault();
                          const nextRow = index + 1;
                          if (nextRow < items.length) {
                            const el = document.querySelector<HTMLElement>(`[data-row-product="${nextRow}"]`);
                            el?.focus();
                          } else {
                            addItem();
                            setTimeout(() => {
                              const el = document.querySelector<HTMLElement>(`[data-row-product="${nextRow}"]`);
                              el?.focus();
                            }, 80);
                          }
                        }
                      }}
                      className="w-full px-2 py-1 border border-[#D1D5DB] rounded text-[13px] outline-none focus:border-[#3B82F6] focus:ring-1 focus:ring-[#3B82F6] focus:bg-blue-50 transition-colors text-right font-bold text-blue-700" 
                    />
                  </td>
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <input 
                      type="text" value={item.sqM || '0.000'} readOnly tabIndex={-1}
                      className="w-full px-2 py-1 border border-[#D1D5DB] rounded bg-[#E5E7EB] text-[13px] outline-none text-right font-bold text-[#4B5563] cursor-not-allowed" 
                    />
                  </td>

                  {/* OUTCOME - Quantity */}
                  <td className="px-2 py-1 border-r border-[#E5E7EB]">
                    <input 
                      type="number" value={item.outcomeQuantity} onChange={e => updateItem(index, 'outcomeQuantity', e.target.value)}
                      placeholder="0" onFocus={e => e.target.select()}
                      readOnly={true}
                      className="w-full px-2 py-1 border border-[#D1D5DB] rounded bg-[#E5E7EB] text-[13px] outline-none text-right font-black text-[#4B5563] cursor-not-allowed" 
                    />
                  </td>

                  <td className="px-2 py-1 text-center">
                    <div className="flex justify-center gap-2">
                      <button 
                        type="button" onClick={addItem} 
                        className="bg-[#10B981] text-white p-1.5 rounded hover:bg-[#059669] transition-colors shadow-sm"
                        title="Add Row"
                      >
                        <Plus size={14} strokeWidth={3} />
                      </button>
                      <button 
                        type="button" onClick={() => removeItem(index)} 
                        disabled={items.length === 1} 
                        className="bg-red-50 text-red-500 p-1.5 rounded hover:bg-red-500 hover:text-white transition-colors disabled:opacity-30 disabled:hover:bg-red-50 disabled:hover:text-red-500"
                        title="Remove Row"
                      >
                        <Trash2 size={14} />
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Footer Calculation Area */}
        <div className="bg-white border-t border-[#E5E7EB] p-3 sm:p-4 shrink-0 shadow-[0_-4px_6px_-1px_rgba(0,0,0,0.05)]">
          <div className="flex flex-col md:flex-row items-stretch md:items-center gap-4 md:gap-6">
            
            <div className="w-full md:flex-1 flex flex-col gap-1">
              <label className="text-[14px] font-extrabold text-[#1F2937] uppercase">Total Quantity Intake:</label>
              <input
                value={items.reduce((acc, item) => acc + (Number(item.intakeQuantity) || 0), 0)}
                readOnly
                className="w-full px-3 py-2 border border-[#D1D5DB] bg-[#FEF2F2] rounded text-[20px] outline-none text-right font-black text-[#991B1B]"
              />
            </div>

            <div className="w-full md:flex-1 flex flex-col gap-1">
              <label className="text-[14px] font-extrabold text-[#1F2937] uppercase">Total Outcome Produced:</label>
              <input
                value={items.reduce((acc, item) => acc + (Number(item.outcomeQuantity) || 0), 0)}
                readOnly
                className="w-full px-3 py-2 border border-[#D1D5DB] bg-[#F0FDF4] rounded text-[20px] outline-none text-right font-black text-[#065F46]"
              />
            </div>
            
            <div className="w-full md:flex-[2] flex flex-col gap-1"></div>

          </div>
        </div>

        {/* Bottom Actions Bar */}
        <div className="bg-white border-t border-gray-200 px-4 py-3 flex flex-col md:flex-row justify-between items-center gap-3 md:gap-0 mt-auto shrink-0">
          <div className="flex flex-nowrap justify-between sm:justify-center gap-1 sm:gap-2 w-full md:w-auto">
            <button 
              type="button" onClick={addItem}
              className="bg-[#2563EB] text-white text-[10px] sm:text-[11px] font-bold px-2 sm:px-3 py-1.5 rounded-sm flex items-center gap-1 cursor-pointer hover:bg-[#1D4ED8] whitespace-nowrap"
            >
              <span className="opacity-70 border-r border-[#60A5FA] pr-1 mr-1">F2</span> Add Row
            </button>

            <button 
              type="button" disabled={mutation.isPending} onClick={() => handleSubmit()}
              className="bg-[#059669] text-white text-[10px] sm:text-[11px] font-bold px-2 sm:px-3 py-1.5 rounded-sm flex items-center gap-1 cursor-pointer hover:bg-[#047857] disabled:opacity-50 disabled:cursor-not-allowed whitespace-nowrap" 
            >
              <span className="opacity-70 border-r border-[#34D399] pr-1 mr-1">F10</span> 
              {mutation.isPending ? 'Saving...' : 'Save Production Entry'}
            </button>
            <button 
              type="button"
              className="bg-[#0891B2] text-white text-[10px] sm:text-[11px] font-bold px-2 sm:px-3 py-1.5 rounded-sm flex items-center gap-1 cursor-pointer hover:bg-[#0E7490] whitespace-nowrap" 
              onClick={() => navigate('/dashboard')}
            >
              <span className="opacity-70 border-r border-[#67E8F9] pr-1 mr-1">Esc</span> Dashboard
            </button>
          </div>
        </div>

      </form>

      {/* ========================================================= */}
      {/* MOBILE-ONLY VIEW (md:hidden)                             */}
      {/* ========================================================= */}

      {/* Mobile Top Header Bar */}
      <div className="md:hidden bg-[#0F172A] text-white px-3 py-2.5 flex items-center justify-between shrink-0 shadow-sm z-20">
        <div className="flex items-center gap-2">
          <button 
            type="button" 
            onClick={() => setShowLeaveModal(true)}
            className="p-1 rounded hover:bg-white/10 active:scale-95 transition-all text-white/90"
          >
            <ArrowLeft size={18} />
          </button>
          <div>
            <h1 className="font-bold text-[13px] tracking-wide flex items-center gap-1.5">
              <Factory size={15} className="text-emerald-400" />
              Grid Entry View
            </h1>
            <p className="text-[10px] text-slate-400 font-mono">
              {batchCode || 'Batch Production'}
            </p>
          </div>
        </div>

        <div className="flex items-center gap-1.5">
          <button 
            type="button" 
            onClick={() => { if (onSwitchToMaster) onSwitchToMaster(); }}
            className="p-1.5 rounded bg-white/10 hover:bg-white/20 text-white text-[11px] font-semibold flex items-center gap-1"
          >
            <List size={13} />
            <span>List</span>
          </button>
          <button 
            type="button" 
            onClick={() => navigate('/reports/production')}
            className="p-1.5 rounded bg-purple-600 hover:bg-purple-700 text-white text-[11px] font-semibold flex items-center gap-1"
          >
            <FileText size={13} />
            <span>Report</span>
          </button>
        </div>
      </div>

      {/* Mobile Main Body */}
      <div className="md:hidden flex flex-col flex-1 min-h-0 overflow-hidden bg-slate-50">
        {/* Mobile Header Inputs: Date, Batch, Work Name */}
        <div className="bg-white px-3 py-3 border-b border-slate-200 shrink-0 space-y-2.5 shadow-sm">
          <div className="grid grid-cols-2 gap-2">
            <div>
              <label className="block text-[10px] uppercase font-bold text-slate-500 mb-1">Production Date *</label>
              <input 
                type="date"
                value={date}
                onChange={e => setDate(e.target.value)}
                className="w-full px-2.5 py-1.5 border border-slate-300 rounded-lg text-xs font-semibold text-slate-800 outline-none focus:border-slate-500"
              />
            </div>
            <div>
              <label className="block text-[10px] uppercase font-bold text-slate-500 mb-1">Batch Code</label>
              <input 
                type="text"
                value={batchCode}
                readOnly
                className="w-full px-2.5 py-1.5 border border-slate-200 rounded-lg text-xs font-mono font-bold text-slate-500 bg-slate-100 outline-none"
              />
            </div>
          </div>

          <div>
            <div className="flex items-center justify-between mb-1">
              <label className="text-[10px] uppercase font-bold text-slate-700">Name of Work *</label>
              <button 
                type="button"
                onClick={handleClear}
                className="text-[10px] text-rose-500 hover:text-rose-700 font-semibold flex items-center gap-0.5"
              >
                <RotateCcw size={10} />
                <span>Reset</span>
              </button>
            </div>
            <input 
              type="text"
              value={workName}
              onChange={e => setWorkName(e.target.value)}
              placeholder="e.g. Manufacturing Batch A"
              className="w-full px-3 py-2 border border-slate-300 rounded-lg text-xs font-semibold text-slate-800 outline-none focus:border-emerald-500 focus:ring-1 focus:ring-emerald-500"
            />
          </div>
        </div>

        {/* Mobile Production Cards List */}
        <div className="flex-1 min-h-0 overflow-y-auto p-3 space-y-3">
          {items.map((item, index) => {
            const product = products.find((p: any) => p.id === item.finishedProductId);
            const material = rawMaterials.find((m: any) => m.id === item.rawMaterialId);

            return (
              <div 
                key={index} 
                className="bg-white rounded-xl border border-slate-200 p-3.5 shadow-sm space-y-3 relative"
              >
                {/* Card Header */}
                <div className="flex items-center justify-between border-b border-slate-100 pb-2">
                  <div className="flex items-center gap-2">
                    <span className="w-5 h-5 rounded-full bg-slate-900 text-white flex items-center justify-center text-[10px] font-bold">
                      {index + 1}
                    </span>
                    <span className="text-xs font-bold text-slate-800">
                      Row #{index + 1}
                    </span>
                  </div>

                  <div className="flex items-center gap-1">
                    <button 
                      type="button" 
                      onClick={addItem}
                      className="p-1 rounded text-emerald-600 hover:bg-emerald-50"
                      title="Add Row"
                    >
                      <Plus size={15} />
                    </button>
                    {items.length > 1 && (
                      <button 
                        type="button" 
                        onClick={() => removeItem(index)}
                        className="p-1 rounded text-rose-500 hover:bg-rose-50"
                        title="Remove Row"
                      >
                        <Trash2 size={15} />
                      </button>
                    )}
                  </div>
                </div>

                {/* 1. Finished Product (Outcome) */}
                <div>
                  <div className="flex items-center justify-between mb-1">
                    <label className="text-[11px] font-bold text-slate-700">Finished Product (Outcome) *</label>
                    {product && (
                      <span className="text-[10px] text-slate-500 font-medium">
                        Area: {product.sqM || '0.000'} m²
                      </span>
                    )}
                  </div>
                  <SearchableSelect
                    value={item.finishedProductId}
                    onChange={(val) => updateItem(index, 'finishedProductId', Number(val))}
                    placeholder="Select product..."
                    options={[
                      { label: 'Select product...', value: 0 },
                      ...finishedProducts.map((p: any) => ({ label: `${p.name} (Stock: ${p.currentStock})`, value: p.id }))
                    ]}
                  />
                </div>

                {/* 2. Raw Material (Intake) */}
                <div>
                  <div className="flex items-center justify-between mb-1">
                    <label className="text-[11px] font-bold text-slate-700">Raw Material (Intake) *</label>
                    {material && (
                      <span className="text-[10px] text-slate-500 font-medium">
                        Stock: <strong className={material.currentStock > 0 ? 'text-slate-800' : 'text-rose-600'}>{material.currentStock || 0}</strong>
                      </span>
                    )}
                  </div>
                  <SearchableSelect
                    value={item.rawMaterialId}
                    onChange={(val) => updateItem(index, 'rawMaterialId', Number(val))}
                    placeholder="Select material..."
                    options={[
                      { label: 'Select material...', value: 0 },
                      ...rawMaterials.map((m: any) => ({ label: `${m.name}`, value: m.id }))
                    ]}
                  />
                </div>

                {/* 3. Quantities Grid */}
                <div className="grid grid-cols-3 gap-2 pt-1 bg-slate-50/70 p-2.5 rounded-lg border border-slate-100">
                  <div>
                    <label className="block text-[10px] font-bold text-blue-900 mb-1">Intake Qty *</label>
                    <input 
                      type="number"
                      value={item.intakeQuantity}
                      onChange={e => updateItem(index, 'intakeQuantity', e.target.value)}
                      placeholder="0"
                      className="w-full px-2 py-1.5 border border-blue-200 bg-white rounded-lg text-xs font-bold text-blue-700 text-right outline-none focus:border-blue-500 focus:ring-1 focus:ring-blue-500"
                    />
                  </div>

                  <div>
                    <label className="block text-[10px] font-bold text-slate-600 mb-1">Raw Sq.M</label>
                    <input 
                      type="text"
                      value={item.sqM || '0.000'}
                      readOnly
                      tabIndex={-1}
                      className="w-full px-2 py-1.5 border border-slate-200 bg-slate-100 rounded-lg text-xs font-bold text-slate-600 text-right outline-none"
                    />
                  </div>

                  <div>
                    <label className="block text-[10px] font-bold text-emerald-900 mb-1">Outcome Qty</label>
                    <input 
                      type="number"
                      value={item.outcomeQuantity}
                      onChange={e => updateItem(index, 'outcomeQuantity', e.target.value)}
                      readOnly
                      placeholder="0"
                      className="w-full px-2 py-1.5 border border-emerald-200 bg-emerald-50/50 rounded-lg text-xs font-bold text-emerald-700 text-right outline-none"
                    />
                  </div>
                </div>
              </div>
            );
          })}

          {/* Add Another Row Button */}
          <button 
            type="button"
            onClick={addItem}
            className="w-full py-2.5 border-2 border-dashed border-slate-300 hover:border-slate-400 text-slate-600 rounded-xl text-xs font-bold flex items-center justify-center gap-1.5 bg-white hover:bg-slate-50 transition-all active:scale-[0.99]"
          >
            <Plus size={15} />
            <span>Add Another Production Row</span>
          </button>
        </div>

        {/* Mobile Sticky Bottom Summary & CTA */}
        <div className="bg-white border-t border-slate-200 p-3 shrink-0 shadow-[0_-4px_12px_rgba(0,0,0,0.06)] space-y-2">
          <div className="grid grid-cols-2 gap-2 text-xs">
            <div className="bg-rose-50 border border-rose-100 rounded-lg px-2.5 py-1.5 flex items-center justify-between">
              <span className="text-[10px] uppercase font-bold text-rose-800">Total Intake:</span>
              <span className="font-black text-rose-700 text-sm">
                {items.reduce((acc, item) => acc + (Number(item.intakeQuantity) || 0), 0)}
              </span>
            </div>
            <div className="bg-emerald-50 border border-emerald-100 rounded-lg px-2.5 py-1.5 flex items-center justify-between">
              <span className="text-[10px] uppercase font-bold text-emerald-800">Total Outcome:</span>
              <span className="font-black text-emerald-700 text-sm">
                {items.reduce((acc, item) => acc + (Number(item.outcomeQuantity) || 0), 0)}
              </span>
            </div>
          </div>

          <button 
            type="button"
            disabled={mutation.isPending}
            onClick={() => handleSubmit()}
            className="w-full bg-emerald-600 hover:bg-emerald-700 text-white py-3 rounded-xl font-bold text-xs flex items-center justify-center gap-2 shadow-lg shadow-emerald-600/30 active:scale-95 transition-all disabled:opacity-50"
          >
            <CheckCircle size={16} />
            <span>{mutation.isPending ? 'Saving Production...' : 'SAVE PRODUCTION ENTRY'}</span>
          </button>
        </div>
      </div>
      <LeaveConfirmModal 
        isOpen={showLeaveModal}
        onConfirm={() => navigate('/dashboard')}
        onClose={() => setShowLeaveModal(false)}
      />
    </div>
  );
};

export default ProductionGridEntry;
